#!/usr/bin/env python3
"""Writes a logging stub for every kernel/XAM function the recompiled game imports.

    python -I runtime/gen_import_stubs.py <ppc_recomp_shared.h> <out.cpp> <kernel-dir>

Imports already implemented in <kernel-dir> (any `PPC_FUNC(__imp__Name)` definition in
a .cpp file there) are left out. The output is only rewritten when it changes.
"""

import os
import re
import sys


def main(header, out, kernel_dir):
    with open(header, encoding="utf-8") as f:
        imports = re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\);", f.read())
    implemented = set()
    for root, _, files in os.walk(kernel_dir):
        for name in files:
            if name.endswith(".cpp"):
                with open(os.path.join(root, name), encoding="utf-8") as f:
                    implemented |= set(re.findall(r"PPC_FUNC\(__imp__(\w+)\)", f.read()))
    stubs = [n for n in imports if n not in implemented]

    text = (
        "// Generated by runtime/gen_import_stubs.py from ppc_recomp_shared.h. Do not edit.\n"
        "// One logging stub per imported kernel/XAM function not implemented in runtime/kernel.\n\n"
        '#include "kernel/kernel.h"\n\n'
        + "".join(f'PPC_FUNC(__imp__{n}) {{ s3n::kernel::UnimplementedImport(ctx, base, "{n}"); }}\n' for n in stubs)
    )
    old = None
    if os.path.exists(out):
        with open(out, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"{len(imports)} imports: {len(imports) - len(stubs)} implemented, {len(stubs)} stubbed")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
