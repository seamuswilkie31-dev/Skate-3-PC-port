# Writes third_party/ffmpeg/sources.cmake: the C files FFmpeg's own makefiles would compile
# for libavutil and libavcodec under a configure result (scripts/ffmpeg_config.ps1).
#
#   python -I ffmpeg_sources.py <ffmpeg source> <configure folder> <sources.cmake>
#
# FFmpeg builds with make, which isn't part of this project's toolchain, so the makefiles'
# object lists are evaluated here instead: OBJS and STLIBOBJS, plus their -$(CONFIG_X) and
# -$(HAVE_X) variants when configure enabled X, in each library's Makefile and x86/Makefile.

import os
import re
import sys

source, configured, output = sys.argv[1:4]

enabled = set()
with open(os.path.join(configured, 'ffbuild', 'config.mak'), encoding='utf-8', errors='replace') as mak:
    for line in mak:
        if m := re.match(r'^([A-Z0-9_]+)=yes\s*$', line):
            enabled.add(m.group(1))

CONTINUATION = chr(92)


def logical_lines(path):
    pending = ''
    with open(path, encoding='utf-8', errors='replace') as makefile:
        for line in makefile:
            line = line.rstrip('\n')
            if line.endswith(CONTINUATION):
                pending += line[:-1] + ' '
                continue
            yield pending + line
            pending = ''


def objects(path):
    found = set()
    for line in logical_lines(path):
        m = re.match(r'^\s*(?:OBJS|STLIBOBJS)(?:-\$\(([A-Z0-9_]+)\))?\s*\+?=\s*(.*)$', line)
        if not m or (m.group(1) and m.group(1) not in enabled):
            continue
        found.update(word for word in m.group(2).split() if word.endswith('.o') and '$' not in word)
    return found


with open(output, 'w', encoding='utf-8', newline='\n') as out:
    out.write('# Generated by scripts/ffmpeg_sources.py from FFmpeg\'s makefiles; do not edit.\n')
    for library in ('avutil', 'avcodec'):
        folder = os.path.join(source, 'lib' + library)
        names = objects(os.path.join(folder, 'Makefile'))
        if os.path.exists(os.path.join(folder, 'x86', 'Makefile')):
            names |= objects(os.path.join(folder, 'x86', 'Makefile'))
        files = sorted(f'lib{library}/{name[:-2]}.c' for name in names)
        missing = [f for f in files if not os.path.exists(os.path.join(source, f))]
        if missing:
            sys.exit('not in the FFmpeg source: ' + ', '.join(missing))
        out.write(f'set(FFMPEG_{library.upper()}_SOURCES\n')
        out.writelines(f'    {f}\n' for f in files)
        out.write(')\n')
    print(f'wrote {output}')
